// Test data for developers and QA: a new made-up person on every fill.
// Everything is fictional and safe: example.com emails, 555-01xx numbers, no payment or ID data.

const FIRST = ['Aarav', 'Maya', 'Liam', 'Sofia', 'Noah', 'Priya', 'Ethan', 'Zara', 'Lucas', 'Ananya', 'Mateo', 'Hana', 'Oliver', 'Amara', 'Kai', 'Elena']
const LAST = ['Sharma', 'Nguyen', 'Garcia', 'Okafor', 'Müller', 'Rossi', 'Tanaka', 'Silva', 'Kowalski', 'Haddad', 'Larsen', 'Iyer', "O'Brien", 'Kim', 'Patel', 'Novak']
const COMPANIES = ['Acme Corp', 'Globex', 'Initech', 'Umbrella Labs', 'Stark Industries', 'Hooli', 'Wayne Enterprises', 'Soylent']
const TITLES = ['Software Engineer', 'Product Designer', 'Data Analyst', 'QA Engineer', 'Product Manager', 'Frontend Developer']
const SCHOOLS = ['State University', 'Institute of Technology', 'City College', 'National University']
const DEGREES = ["Bachelor's", "Master's", 'B.Tech', 'MBA']
const FIELDS_OF_STUDY = ['Computer Science', 'Design', 'Mathematics', 'Business']
const STREETS = ['Main Street', 'Oak Avenue', 'Maple Road', 'Park Lane', 'Elm Street', 'Lake View']
const PLACES = [
  { country: 'United States', state: 'California', city: 'San Francisco', zip: () => '941' + digits(2), phone: () => `+1 415 555 01${digits(2)}` },
  { country: 'United States', state: 'New York', city: 'New York', zip: () => '100' + digits(2), phone: () => `+1 212 555 01${digits(2)}` },
  { country: 'India', state: 'Karnataka', city: 'Bengaluru', zip: () => '5600' + digits(2), phone: () => `+91 90000 ${digits(5)}` },
  { country: 'United Kingdom', state: 'England', city: 'London', zip: () => `SW1A ${digits(1)}AA`, phone: () => `+44 20 7946 0${digits(3)}` },
  { country: 'Canada', state: 'Ontario', city: 'Toronto', zip: () => `M5V ${digits(1)}A${digits(1)}`, phone: () => `+1 416 555 01${digits(2)}` },
]

let rand = Math.random
const pick = (list) => list[Math.floor(rand() * list.length)]
const digits = (n) => Array.from({ length: n }, () => Math.floor(rand() * 10)).join('')
const slug = (s) => s.normalize('NFD').replace(/[^\w]/g, '').toLowerCase()

// Deterministic generator for tests.
export function seededRandom(seed) {
  let a = seed >>> 0
  return () => {
    a = (a + 0x6d2b79f5) >>> 0
    let t = a
    t = Math.imul(t ^ (t >>> 15), t | 1)
    t ^= t + Math.imul(t ^ (t >>> 7), t | 61)
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296
  }
}

export function makeTestProfile(random = Math.random) {
  rand = random
  try {
    const firstName = pick(FIRST)
    const lastName = pick(LAST)
    const place = pick(PLACES)
    const handle = `${slug(firstName)}.${slug(lastName)}`
    const tag = digits(4)
    const year = 1975 + Math.floor(rand() * 30)
    const dob = `${year}-${String(1 + Math.floor(rand() * 12)).padStart(2, '0')}-${String(1 + Math.floor(rand() * 28)).padStart(2, '0')}`
    const company = pick(COMPANIES)
    const jobTitle = pick(TITLES)
    return {
      fullName: `${firstName} ${lastName}`,
      firstName,
      middleName: '',
      lastName,
      username: `${handle.replace('.', '_')}${tag}`,
      dob,
      gender: pick(['Female', 'Male']),
      // "+tag" keeps each run unique for sign-up forms that reject repeat emails.
      email: `${handle}+${tag}@example.com`,
      phone: place.phone(),
      phone2: '',
      company,
      jobTitle,
      address1: `${1 + Math.floor(rand() * 999)} ${pick(STREETS)}`,
      address2: rand() < 0.3 ? `Apt ${1 + Math.floor(rand() * 40)}` : '',
      city: place.city,
      state: place.state,
      zip: place.zip(),
      country: place.country,
      website: `https://${slug(lastName)}.example.com`,
      linkedin: `https://www.linkedin.com/in/${handle.replace('.', '-')}-${tag}`,
      github: `https://github.com/${slug(firstName)}${tag}`,
      portfolio: '',
      yearsExperience: String(1 + Math.floor(rand() * 15)),
      currentCtc: '',
      expectedCtc: '',
      noticePeriod: pick(['Immediate', '2 weeks', '30 days']),
      bio: `${jobTitle} at ${company}. Test profile generated by SmartFill.`,
      school: `${place.city} ${pick(SCHOOLS)}`,
      degree: pick(DEGREES),
      fieldOfStudy: pick(FIELDS_OF_STUDY),
      graduationYear: String(year + 22),
      answers: [],
      resume: null,
      customFields: [],
    }
  } finally {
    rand = Math.random
  }
}
